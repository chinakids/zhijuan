// ===== 织卷 · Markdown 元信息注释（HTML 注释）工具 =====
// 语义约定（2026-09-11 落实）：`<!-- … -->` 是写给「人/作者」的元信息（模板说明、占位提示、备忘），
// 不是故事事实/设定内容——可视化渲染里注释本就不可见。
// 因此装配给写作引擎的上下文一律剥离注释（模型看到的是事实，不是说明文字）；
// 模型要「看」注释原文仍可 zj_read_doc 现读（工具直读文件原文，不受本函数影响）。
// 口径与 context.ts 的 isTemplateShell 一致：只剥「成对闭合」注释（`<!-- … -->`）；
// 未闭合的 `<!--` 视为手误/正文的一部分，**原样保留**（不吞后面的正文，宁可保留不可误删）。
export function stripHtmlComments(text: string): string {
  return text.replace(/<!--[\s\S]*?-->/g, '')
}
