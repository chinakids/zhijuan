/**
 * 人物档案模板（单一权威源，2026-09-15 创作层从 ProjectGuide 抽出——守卫「快速建档」与项目引导共用，防两处形态漂移）。
 *
 * 口径（2026-09-11）：占位说明一律用 HTML 注释——切片小节由引擎在正文保存时按「切片名」自然生成；
 * 预置死节会在真实切片名下永不清理，且随人物档全文件进 agent 上下文污染提示词。
 * 占位口径（2026-09-21 创作层，候选 3 收口）：引导模板的「（身份 / 职业）」等括号占位是「作者待填项」的正规形态，
 * 保留（同 templates.ts 示例档——教学语境展示字段）；快速建档模板（quickCharDocMarkdown）的占位统一带「待补充：」前缀
 * ——真实创作语境下该占位会留在盘上并随档案进 agent 上下文，无「待补充」信号易被误读为「AI 已填内容」。
 * 两语境占位形态不同（示例模板=教学语境展示字段取值 vs 快速建档=待填提示），函数职责单源注释说明，勿互相迁移。
 */

/** 项目引导建档模板（行为与引导原版逐字符一致：role/traits 为空则原样写出） */
export function charDocMarkdown(name: string, role: string, traits: string): string {
  return (
    `---\n别名: []\n---\n` +
    `# ${name}\n\n` +
    `> 定位：${role}\n` +
    `> 关键特征：${traits}\n\n` +
    `## 基础档案\n\n` +
    `（年龄 / 外貌 / 背景 / 性格取向，按需补写）\n\n` +
    `<!-- 正文保存时，切片同步会把 TA 在本章的新状态写入「## 切片：<切片名>」小节（没有则自动追加）；基础档案是长期设定，请在这里手动维护，勿与切片小节混写。 -->\n` +
    `<!-- 若 TA 在正文里还有别的称呼（昵称/化名），把「别名: [小七, 七爷]」写进顶部 front matter——「在场/称谓」机械检查会按它识别。 -->\n`
  )
}

/** 守卫「快速建档」模板：只有人名，定位/特征留占位——统一「（待补充：…）」形态（作者待填项显式标注，防「AI 已填」误解；2026-09-21 候选 3） */
export function quickCharDocMarkdown(name: string): string {
  return charDocMarkdown(name, '（待补充：身份 / 职业）', '（待补充：关键特征）')
}
